// Builds supabase/milkyway-schema-repair.sql: ONE idempotent script that brings an older (drifted) Supabase database up
// to the layout the API expects, then (re)creates every function from supabase/migrations.
//
// Why it is needed: the live project still has an older table layout (for example mw_message_hides.owner_id instead
// of user_id, mw_dm_calls without callee_id/offer/answer/ended_at, no wallet tables), and the files in
// supabase/migrations were never applied. Those files use `create table if not exists`, which skips existing tables,
// so on their own they would stop at the first column the old tables lack.
//
// The script, inside one transaction (all or nothing):
//   1. renames/sets aside legacy shapes that cannot be patched in place,
//   2. adds every missing column of every table the migrations define (nullable when the old rows cannot fill it),
//      plus the unique indexes that upserts (`on conflict`) rely on,
//   3. copies data from legacy columns into the new ones and relaxes NOT NULL on legacy columns the app no longer writes,
//   4. runs all migrations in order (their own begin/commit removed),
//   5. locks direct messages away from the anonymous role and reloads the PostgREST schema cache.
//
// Usage: node tools/build-supabase-repair.mjs   → paste supabase/milkyway-schema-repair.sql into the Supabase SQL editor.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'migrations');
// Needs a webhook secret filled in by hand and the pg_net extension; apply it separately when push relay is wanted.
const SKIP = new Set(['20261016_milkyway_fcm_event_relay.sql']);
const files = readdirSync(dir).filter(name => name.endsWith('.sql') && !SKIP.has(name)).sort();

const quote = value => `'${String(value).replace(/'/g, "''")}'`;

// Splits "a, b (c, d), e" on top-level commas only.
function splitTop(body) {
  const parts = [];
  let depth = 0, current = '';
  for (const ch of body) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { parts.push(current); current = ''; } else current += ch;
  }
  parts.push(current);
  return parts.map(part => part.replace(/--[^\n]*/g, '').trim()).filter(Boolean);
}

// Removes `check ( … )` with balanced parentheses.
function stripChecks(text) {
  let out = '', i = 0;
  const re = /\bcheck\s*\(/gi;
  let match;
  while ((match = re.exec(text))) {
    out += text.slice(i, match.index);
    let depth = 1, j = match.index + match[0].length;
    while (j < text.length && depth) { if (text[j] === '(') depth++; else if (text[j] === ')') depth--; j++; }
    i = j; re.lastIndex = j;
  }
  return (out + text.slice(i)).replace(/\s+/g, ' ').trim();
}

const tables = new Map(); // name → { columns: Map(name → { def, plain }), keys: [[cols]] }
for (const file of files) {
  const sql = readFileSync(join(dir, file), 'utf8');
  for (const match of sql.matchAll(/create table if not exists public\.(\w+)\s*\(([\s\S]*?)\n\);/gi)) {
    const [, table, body] = match;
    const entry = tables.get(table) || { columns: new Map(), keys: [] };
    tables.set(table, entry);
    for (const part of splitTop(body)) {
      const keyMatch = /^(?:constraint\s+\w+\s+)?(primary key|unique)\s*\(([^)]*)\)/i.exec(part);
      if (keyMatch) { entry.keys.push(keyMatch[2].split(',').map(col => col.trim())); continue; }
      if (/^(constraint|check|foreign|exclude)\b/i.test(part)) continue;
      const [name, ...rest] = part.split(/\s+/);
      let def = rest.join(' ');
      if (/\b(primary key|unique)\b/i.test(def)) entry.keys.push([name]);
      def = stripChecks(def.replace(/\bprimary key\b/gi, '').replace(/\bunique\b/gi, ''));
      if (!/\bdefault\b/i.test(def) && !/\bgenerated\b/i.test(def)) def = def.replace(/\bnot null\b/gi, '');
      def = def.replace(/\s+/g, ' ').trim();
      const plain = def.replace(/\breferences\s+[\w.]+\s*\([^)]*\)(\s+on\s+(delete|update)\s+(cascade|set null|restrict|no action))*/gi, '').replace(/\s+/g, ' ').trim();
      if (!entry.columns.has(name)) entry.columns.set(name, { def, plain });
    }
  }
}

const out = [];
const add = (...lines) => out.push(...lines);

add(
  '-- MilkyWay Supabase schema repair. GENERATED by tools/build-supabase-repair.mjs from supabase/migrations — do not edit by hand.',
  '-- Safe to run more than once. Paste the whole file into Supabase → SQL Editor → Run. It runs as one transaction:',
  '-- if anything fails, nothing is changed. Notices starting with "MilkyWay repair" list steps that were skipped.',
  '',
  'begin;',
  '',
  '-- ---------------------------------------------------------------------------------------------------------------',
  '-- Helpers (dropped again at the end)',
  '-- ---------------------------------------------------------------------------------------------------------------',
  `create or replace function public.mw_repair_try(stmt text) returns void language plpgsql as $$
begin
  execute stmt;
exception when others then
  raise notice 'MilkyWay repair skipped: % (%)', stmt, sqlerrm;
end $$;`,
  `create or replace function public.mw_repair_has(t text, c text) returns boolean language sql stable as $$
  select exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = t and column_name = c)
$$;`,
  `create or replace function public.mw_repair_add(t text, c text, def text, plain text) returns void language plpgsql as $$
begin
  if to_regclass(format('public.%I', t)) is null or public.mw_repair_has(t, c) then return; end if;
  begin
    execute format('alter table public.%I add column %I %s', t, c, def);
  exception when others then
    -- usually a foreign key the old rows cannot satisfy: add the column without it
    perform public.mw_repair_try(format('alter table public.%I add column %I %s', t, c, plain));
  end;
end $$;`,
  `create or replace function public.mw_repair_key(t text, cols text[]) returns void language plpgsql as $$
begin
  if to_regclass(format('public.%I', t)) is null then return; end if;
  if exists (select 1 from unnest(cols) col where not public.mw_repair_has(t, col)) then return; end if;
  perform public.mw_repair_try(format('create unique index if not exists %I on public.%I (%s)',
    left('mw_repair_' || t || '_' || array_to_string(cols, '_') || '_key', 63), t,
    (select string_agg(format('%I', col), ', ') from unnest(cols) col)));
end $$;`,
  `create or replace function public.mw_repair_copy(t text, src text, dst text, force boolean default false) returns void language plpgsql as $$
declare kind text;
begin
  if not (public.mw_repair_has(t, src) and public.mw_repair_has(t, dst)) then return; end if;
  select format_type(a.atttypid, a.atttypmod) into kind from pg_attribute a where a.attrelid = to_regclass(format('public.%I', t)) and a.attname = dst;
  perform public.mw_repair_try(format('update public.%I set %I = %I::%s where (%s or %I is null) and %I is not null', t, dst, src, kind, force, dst, src));
end $$;`,
  `create or replace function public.mw_repair_relax(t text, keep text[]) returns void language plpgsql as $$
declare col text;
begin
  if to_regclass(format('public.%I', t)) is null then return; end if;
  for col in
    select a.attname from pg_attribute a
    where a.attrelid = to_regclass(format('public.%I', t)) and a.attnum > 0 and not a.attisdropped
      and a.attnotnull and not a.atthasdef and a.attidentity = '' and not (a.attname = any(keep))
  loop
    perform public.mw_repair_try(format('alter table public.%I alter column %I drop not null', t, col));
  end loop;
end $$;`,
  '',
  '-- ---------------------------------------------------------------------------------------------------------------',
  '-- 1. Legacy shapes',
  '-- ---------------------------------------------------------------------------------------------------------------',
  '-- "Delete for me" rows: owner_id → user_id (the API filters and upserts on user_id, message_id).',
  `do $$ begin
  if public.mw_repair_has('mw_message_hides', 'owner_id') and not public.mw_repair_has('mw_message_hides', 'user_id') then
    alter table public.mw_message_hides rename column owner_id to user_id;
  end if;
end $$;`,
  '-- The old wallet settings table is a key/value list; the wallet functions need the single-row layout. Keep the old one aside.',
  `do $$ begin
  if to_regclass('public.mw_wallet_settings') is not null and not public.mw_repair_has('mw_wallet_settings', 'id')
     and to_regclass('public.mw_wallet_settings_legacy') is null then
    alter table public.mw_wallet_settings rename to mw_wallet_settings_legacy;
  end if;
end $$;`,
  '-- Old call status rules may not allow accepted/declined.',
  `do $$ declare c record; begin
  for c in select conname from pg_constraint where conrelid = to_regclass('public.mw_dm_calls') and contype = 'c'
            and pg_get_constraintdef(oid) ilike '%status%' loop
    execute format('alter table public.mw_dm_calls drop constraint %I', c.conname);
  end loop;
end $$;`,
  '-- Direct messages were readable with the public key. Drop wide-open read policies so only the two people in a chat can read it.',
  `do $$ declare p record; begin
  for p in select policyname from pg_policies where schemaname = 'public' and tablename = 'mw_messages'
            and cmd in ('SELECT', 'ALL') and coalesce(qual, 'true') = 'true' loop
    execute format('drop policy %I on public.mw_messages', p.policyname);
  end loop;
end $$;`,
  '',
  '-- ---------------------------------------------------------------------------------------------------------------',
  '-- 2. Missing columns and upsert keys on tables that already exist',
  '-- ---------------------------------------------------------------------------------------------------------------',
);
for (const [table, { columns, keys }] of tables) {
  add(`-- ${table}`);
  for (const [name, { def, plain }] of columns) add(`select public.mw_repair_add(${quote(table)}, ${quote(name)}, ${quote(def)}, ${quote(plain)});`);
  for (const cols of keys) add(`select public.mw_repair_key(${quote(table)}, array[${cols.map(quote).join(', ')}]);`);
}
add(
  '',
  '-- ---------------------------------------------------------------------------------------------------------------',
  '-- 3. Carry legacy data over and stop legacy NOT NULL columns from blocking new rows',
  '-- ---------------------------------------------------------------------------------------------------------------',
  "select public.mw_repair_copy('mw_message_hides', 'hidden_at', 'created_at', true);",
  "select public.mw_repair_copy('mw_dm_group_messages', 'message', 'body');",
  "select public.mw_repair_copy('mw_live_room_messages', 'message', 'body');",
  "select public.mw_repair_copy('mw_live_room_messages', 'room_id', 'room_name');",
  "select public.mw_repair_copy('mw_live_alerts', 'room', 'room_name');",
);
for (const [table, { columns }] of tables) add(`select public.mw_repair_relax(${quote(table)}, array[${[...columns.keys()].map(quote).join(', ')}]);`);
add('');

for (const file of files) {
  const sql = readFileSync(join(dir, file), 'utf8').replace(/^\s*(begin|commit)\s*;\s*$/gim, '');
  add(
    '-- ===============================================================================================================',
    `-- supabase/migrations/${file}`,
    '-- ===============================================================================================================',
    sql.trim(),
    '',
  );
}

add(
  '-- ---------------------------------------------------------------------------------------------------------------',
  '-- 5. Final hardening and cleanup',
  '-- ---------------------------------------------------------------------------------------------------------------',
  'alter table public.mw_messages enable row level security;',
  'revoke all on public.mw_messages from anon;',
  'drop function if exists public.mw_repair_relax(text, text[]);',
  'drop function if exists public.mw_repair_copy(text, text, text, boolean);',
  'drop function if exists public.mw_repair_key(text, text[]);',
  'drop function if exists public.mw_repair_add(text, text, text, text);',
  'drop function if exists public.mw_repair_has(text, text);',
  'drop function if exists public.mw_repair_try(text);',
  '',
  'commit;',
  '',
  '-- Make the API see the new functions and columns right away (fixes "Could not find the function … in the schema cache").',
  "notify pgrst, 'reload schema';",
  '',
);

const target = join(root, 'supabase', 'milkyway-schema-repair.sql');
writeFileSync(target, out.join('\n'));
console.log(`Wrote ${target} (${tables.size} tables, ${files.length} migrations).`);
